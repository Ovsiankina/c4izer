//! Speed budgets of the core (SRS 5.2), run by the release perf oracle:
//! `cargo test --workspace --release -- --ignored perf_`. Every test is
//! `#[ignore]`d so a debug `cargo test` skips it; the timed view is `c3`
//! of `tests/data/example.dsl`, the heaviest (pipeline-03).
//!
//! A timing run in a debug build means nothing, so each `perf_` test
//! prints a note and returns when `debug_assertions` are on.

// DECISION: "view `c3`" of the SRS is the prototype's `c3.svg`, keyed
// `C3-serving` in `tests/data/example.dsl` (the converted example keeps
// the prototype's view keys; its other C3 view is `C3-startup`).
// DECISION: the CORE-31 file places every box by an `at` line on a
// fixed grid, so the timed work is routing (SRS 5.2: the hot path) and
// does not shift when `place` changes; the seeded random pairs make it a
// tangle (232 crossings), a stress case rather than a tidy diagram.
// DECISION: each budget is checked on the median of 5 timed runs after
// one untimed warm-up run, so one scheduler hiccup does not fail the
// oracle while a real regression (every run slower) still does.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::sync::atomic::AtomicBool;
use std::time::{Duration, Instant};

use c4rizer_core::geom::Point;
use c4rizer_core::model::{Model, parse};
use c4rizer_core::pipeline::{PREVIEW_ROUTE, build_view, keep_across_reparse, rebuild_after_move};
use c4rizer_core::place::{self, Keep};

const EXAMPLE: &str = include_str!(concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../tests/data/example.dsl"
));

/// The plain Structurizr example (no `at` lines): every view goes through
/// the layered placement (P2-111).
const WORKSPACE: &str = include_str!(concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../tests/data/example/workspace.dsl"
));

/// The CORE-31 view: 40 boxes, 60 lines, generated by `generated()`
/// from `SEED` and checked in.
const GENERATED: &str = include_str!(concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/tests/data/core_31_generated.dsl"
));

const C3: &str = "C3-serving";
const RUNS: usize = 5;

/// True (after printing why) when this is not a release build.
fn debug_build(test: &str) -> bool {
    if cfg!(debug_assertions) {
        println!("{test}: skipped, timing needs `cargo test --release`");
        return true;
    }
    false
}

/// The median wall time of `RUNS` runs of `f`, after one warm-up run.
fn median(mut f: impl FnMut()) -> Duration {
    f();
    let mut times: Vec<Duration> = (0..RUNS)
        .map(|_| {
            let t = Instant::now();
            f();
            t.elapsed()
        })
        .collect();
    times.sort();
    times[RUNS / 2]
}

fn model(src: &str) -> Model {
    match parse(src) {
        Ok(p) => p.model,
        Err(e) => panic!("{e}"),
    }
}

fn go() -> AtomicBool {
    AtomicBool::new(false)
}

fn check(test: &str, took: Duration, budget_ms: u64) {
    println!("{test}: median {:.1} ms (budget {budget_ms} ms)", took.as_secs_f64() * 1e3);
    assert!(
        took < Duration::from_millis(budget_ms),
        "{test}: {took:?}, budget {budget_ms} ms"
    );
}

/// CORE-24: on view `c3` of the example, one box moved then a full
/// route (`pipeline::build_view` with that box in `Keep::moved`) takes
/// under 100 ms in a release build.
// TODO(srs): CORE-24 budget to be confirmed after the first release
// measurement (already open in SRS 4.2).
#[test]
#[ignore = "perf: release perf oracle only"]
fn perf_core_24_rerender_after_move_under_100ms() {
    if debug_build("perf_core_24") {
        return;
    }
    let m = model(EXAMPLE);
    let before = build_view(&m, C3, &Keep::default(), &go()).expect("builds");
    // `mail` two cells right: clear of every other box, every line
    // touching it re-routed in the full route.
    let mail = before.plan.boxes_of(m.find("mail").expect("mail"))[0];
    let at = before.scene.centres[mail.0 as usize];
    let mut keep = Keep::from_previous(&before.plan, &before.scene.centres);
    keep.moved = BTreeMap::from([(mail, Point::new(at.x + 2, at.y))]);
    let mut after = None;
    let took = median(|| {
        after = Some(build_view(&m, C3, &keep, &go()).expect("builds"));
    });
    let after = after.expect("ran");
    assert_eq!(after.scene.centres[mail.0 as usize], Point::new(at.x + 2, at.y));
    assert!(after.routes.unroutable().is_empty());
    check("perf_core_24", took, 100);
}

