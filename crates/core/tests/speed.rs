/// EDIT-29: the core's share of a reload of `tests/data/example.dsl`
/// after a save from another program: `model::parse` of the new text,
/// `pipeline::keep_across_reparse` from the scene on screen, then
/// `pipeline::build_view` of `c3` with that `Keep`, under 200 ms in a
/// release build. The file-event latency and the hand-off to the canvas
/// outside the core and left to the editor contract (not timed here).
#[test]
#[ignore = "perf: release perf oracle only"]
fn perf_edit_29_reload_view_under_200ms() {
    if debug_build("perf_edit_29") {
        return;
    }
    let old = model(EXAMPLE);
    let shown = build_view(&old, C3, &Keep::default(), &go()).expect("builds");
    // The other program's save: one description changed.
    let saved = EXAMPLE.replace(
        "Sends invite and password-reset emails.",
        "Sends invite, password-reset and reminder emails.",
    );
    assert_ne!(saved, EXAMPLE);
    let mut lines = 0;
    let took = median(|| {
        let new = model(&saved);
        let keep = keep_across_reparse(&old, &shown.plan, &shown.scene.centres, &new);
        let b = build_view(&new, C3, &keep, &go()).expect("builds");
        lines = b.scene.lines.len();
    });
    assert_eq!(lines, shown.scene.lines.len());
    check("perf_edit_29", took, 200);
}

/// The fixed seed of the CORE-31 file.
const SEED: u64 = 0x00C4_0031;
const BOXES: usize = 40;
const LINES: usize = 60;
const COLUMNS: usize = 8;

/// `SplitMix64`: a fixed, portable sequence for the generated file.
struct SplitMix(u64);

impl SplitMix {
    fn next(&mut self) -> u64 {
        self.0 = self.0.wrapping_add(0x9E37_79B9_7F4A_7C15);
        let mut z = self.0;
        z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
        z ^ (z >> 31)
    }

    fn below(&mut self, n: usize) -> usize {
        usize::try_from(self.next() % u64::try_from(n).expect("small")).expect("small")
    }
}

/// The CORE-31 file: one software system with 40 containers on an 8 x 5
/// grid (340px by 280px pitch, every box placed by an `at` line, so the
/// timing is routing, not placement) and 60 distinct relationships
/// between random pairs drawn from `SEED`.
fn generated() -> String {
    let mut rng = SplitMix(SEED);
    let mut pairs = std::collections::BTreeSet::new();
    let mut order = Vec::new();
    while order.len() < LINES {
        let (a, b) = (rng.below(BOXES), rng.below(BOXES));
        if a != b && pairs.insert((a, b)) {
            order.push((a, b));
        }
    }
    let mut s = String::from(
        "// CORE-31 speed test data: generated by crates/core/tests/speed.rs\n\
         // (`generated()`, seed 0x00C40031). Do not edit by hand; run\n\
         // `C4RIZER_BLESS=1 cargo test -p c4rizer-core --test speed` to rewrite.\n\
         workspace \"Generated\" \"CORE-31 speed test data.\" {\n\n    model {\n\
         \x20       system = softwareSystem \"Platform\" \"Generated system.\" {\n",
    );
    for i in 0..BOXES {
        let _ = writeln!(
            s,
            "            s{i:02} = container \"Service {i:02}\" \"Generated service number {i:02}.\" \"Rust\""
        );
    }
    s.push_str("        }\n\n");
    for (a, b) in &order {
        let _ = writeln!(s, "        s{a:02} -> s{b:02} \"Sends work to\" \"HTTPS\"");
    }
    s.push_str(
        "    }\n\n    views {\n        container system \"generated\" \"Generated view\" {\n            include *\n",
    );
    for i in 0..BOXES {
        let (col, row) = (i % COLUMNS, i / COLUMNS);
        let _ = writeln!(s, "            at s{i:02} {} {}", 200 + col * 340, 200 + row * 280);
    }
    s.push_str("        }\n    }\n}\n");
    s
}

/// CORE-31 test data: the checked-in file is `generated()` exactly, so
/// the seed reproduces it; `C4RIZER_BLESS=1` rewrites it.
#[test]
fn core_31_generated_file_is_seeded() {
    let want = generated();
    if std::env::var_os("C4RIZER_BLESS").is_some() {
        let path = concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/tests/data/core_31_generated.dsl"
        );
        std::fs::write(path, &want).expect("write test data");
        return;
    }
    assert_eq!(GENERATED, want, "regenerate with C4RIZER_BLESS=1");
    let m = model(GENERATED);
    let v = m.view("generated").expect("view");
    // Plan only: routing it in a debug build takes tens of seconds.
    let b = c4rizer_core::view::plan(&m, v);
    assert_eq!(v.positions.len(), BOXES);
    assert_eq!(b.boxes.len(), BOXES);
    assert_eq!(b.edges.len(), LINES);
}

