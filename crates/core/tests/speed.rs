/// CORE-31 budget, SRS CORE-31: under 1000 ms (median 845 ms after the
/// route-speed change, 2026-11-15; 3352 ms before it).
const CORE_31_BUDGET_MS: u64 = 1000;

/// P2-111 budgets in ms: `pipeline::build_view` and `place::place` alone.
const P2_111_BUILD_MS: u64 = 1000;
const P2_111_PLACE_MS: u64 = 600;

/// P2-111: on each view of `tests/data/example/workspace.dsl`,
/// `pipeline::build_view` with `Keep::default()` takes under 1000 ms and
/// `place::place` alone under 600 ms (median of 5 after one warm-up, in a
/// release build). Prints both per view before checking any.
#[test]
#[ignore = "perf: release perf oracle only"]
fn perf_p2_111_example_views_under_budget() {
    if debug_build("perf_p2_111") {
        return;
    }
    let m = model(WORKSPACE);
    let mut rows = Vec::new();
    for v in &m.views {
        let plan = c4rizer_core::view::plan(&m, v);
        assert_eq!(plan.unplaced().len(), plan.boxes.len(), "{}", v.key);
        let placed = median(|| {
            let _ = place::place(&plan, &Keep::default());
        });
        let built = median(|| {
            let _ = build_view(&m, &v.key, &Keep::default(), &go()).expect("builds");
        });
        println!(
            "perf_p2_111 {}: build {:.1} ms (budget {P2_111_BUILD_MS}), place {:.1} ms (budget {P2_111_PLACE_MS})",
            v.key,
            built.as_secs_f64() * 1e3,
            placed.as_secs_f64() * 1e3
        );
        rows.push((v.key.clone(), built, placed));
    }
    assert_eq!(rows.len(), 4, "four example views");
    for (key, built, placed) in rows {
        assert!(
            built < Duration::from_millis(P2_111_BUILD_MS),
            "perf_p2_111 {key}: build {built:?}, budget {P2_111_BUILD_MS} ms"
        );
        assert!(
            placed < Duration::from_millis(P2_111_PLACE_MS),
            "perf_p2_111 {key}: place {placed:?}, budget {P2_111_PLACE_MS} ms"
        );
    }
}
